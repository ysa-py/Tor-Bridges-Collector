// Minimal, dependency-free SHA-256 used by gateway ports that need to mirror
// Python's `hashlib.sha256(...).hexdigest()` exactly (e.g. the deterministic
// run-seed in `rotator.py`). Implemented in pure `std` to avoid pulling a new
// crate and to stay within the pinned MSRV (1.75).

